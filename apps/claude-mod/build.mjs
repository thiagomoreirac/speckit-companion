// A hooks module and its tests import only files inside the plugin, so this copies in the board's rules and the demo specs.

import { build } from 'esbuild';
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { join } from 'node:path';

const here = fileURLToPath(new URL('.', import.meta.url));
const repo = join(here, '..', '..');

await build({
    entryPoints: [join(repo, 'apps', 'copilot-canvas', 'com.github.copilot', 'extensions', 'speckit-companion', 'spec-rules.mjs')],
    bundle: true,
    absWorkingDir: repo,
    format: 'esm',
    platform: 'neutral',
    target: 'es2022',
    outfile: join(here, 'hooks', 'vendor', 'board-rules.mjs'),
    banner: { js: '// Generated by apps/claude-mod/build.mjs from apps/copilot-canvas/com.github.copilot/extensions/speckit-companion/spec-rules.mjs. Do not edit.' },
    logLevel: 'warning',
});

const demos = join(repo, 'tooling', 'fixtures', 'demo-project', 'specs');
const fixtures = {};
for (const demo of ['_00_demo-specified', '_01_demo-planned', '_02_demo-tasked', '_03_demo-living']) {
    const files = readdirSync(join(demos, demo), { withFileTypes: true })
        .filter(file => file.isFile() && (file.name === '.spec-context.json' || file.name.endsWith('.md')))
        .map(file => file.name).sort();
    for (const file of files) {
        fixtures[`specs/${demo}/${file}`] = readFileSync(join(demos, demo, file), 'utf8').replace(/\r\n/g, '\n');
    }
}
writeFileSync(
    join(here, 'tests', 'fixtures', 'demo-specs.js'),
    '// Generated by apps/claude-mod/build.mjs from tooling/fixtures/demo-project. Do not edit.\n'
        + `export const DEMO_SPECS = ${JSON.stringify(fixtures, null, 2)}\n`,
);

console.log(`built hooks/vendor/board-rules.mjs and tests/fixtures/demo-specs.js (${Object.keys(fixtures).length} files)`);
